const normKey = (s: string) => s.toLowerCase().replace(/[\s_]+/g, '-');
const byNorm = new Map(Object.entries(PRODUCTS).map(([k, v]) => [normKey(k), v]));

/** A known product name -> [icon name, display label]. */
export function findProduct(key: string): [string, string] | undefined {
  return byNorm.get(normKey(key)) ?? byNorm.get(key.toLowerCase().replace(/[^a-z0-9]/g, ''));
}
