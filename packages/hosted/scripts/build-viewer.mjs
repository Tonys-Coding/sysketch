// Bundle the in-chat viewer (viewer/main.ts + viewer/index.html) into one HTML page and write
// it to src/viewer.generated.ts, which the MCP server serves as its ui:// resource.
// usage: node scripts/build-viewer.mjs (part of `npm run build`)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = (p) => new URL(`../${p}`, import.meta.url);
const out = await build({
  entryPoints: [fileURLToPath(here('viewer/main.ts'))],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = readFileSync(here('viewer/index.html'), 'utf8').replace(
  '<!-- viewer script -->',
  // a function, so `$'` and `$&` in the bundle aren't read as replacement patterns
  () => `<script type="module">${js}</script>`,
);
writeFileSync(
  here('src/viewer.generated.ts'),
  `// Generated by scripts/build-viewer.mjs from viewer/. Do not edit.\nexport const VIEWER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`viewer: ${(html.length / 1024).toFixed(0)} KB`);
