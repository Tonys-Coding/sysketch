// Converts icons-src/*.svg into packages/sysketch/src/icons.generated.ts.
// Run via `npm run icons` (which rebuilds and renders a preview sheet afterwards).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { ICONS, IconImportError, convertIconSvg } from '../packages/sysketch/dist/index.js';

const SRC = 'icons-src';
const OUT = 'packages/sysketch/src/icons.generated.ts';
const names = new Set(ICONS.map((i) => i.name));

// Backups and drafts are skipped: name-old.svg, name.bak.svg, _name.svg.
const isBackup = (f) => /^_|-old\.svg$|\.bak\.svg$/i.test(f);
const all = readdirSync(SRC).filter((f) => f.toLowerCase().endsWith('.svg'));
const backups = all.filter(isBackup).sort();
const files = all.filter((f) => !isBackup(f)).sort();
const generated = {};
let failed = 0;

for (const file of files) {
  const name = basename(file, '.svg').toLowerCase();
  if (!names.has(name)) {
    console.log(`✗ ${file}: unknown icon name. Use a name from docs/icon-checklist.md`);
    failed++;
    continue;
  }
  try {
    const { body, warnings } = convertIconSvg(readFileSync(join(SRC, file), 'utf8'));
    generated[name] = body;
    console.log(`✓ ${name}${warnings.length ? `  (note: ${warnings.join('; ')})` : ''}`);
  } catch (e) {
    if (!(e instanceof IconImportError)) throw e;
    console.log(`✗ ${file}: ${e.message}`);
    failed++;
  }
}

const entries = Object.keys(generated)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}:\n    ${JSON.stringify(generated[k])},`)
  .join('\n');
writeFileSync(
  OUT,
  `// Generated by \`npm run icons\` from icons-src/*.svg. Do not edit by hand.\n` +
    `export const GENERATED_ICONS: Record<string, string> = {${entries ? `\n${entries}\n` : ''}};\n`,
);

// Keep docs/icon-checklist.md in sync: tick drawn icons, refresh the progress line.
const CHECKLIST = 'docs/icon-checklist.md';
if (existsSync(CHECKLIST)) {
  const drawn = new Set(Object.keys(generated));
  const doc = readFileSync(CHECKLIST, 'utf8')
    .replace(/^- \[[ x]\] `([a-z0-9-]+)`/gm, (_, n) => `- [${drawn.has(n) ? 'x' : ' '}] \`${n}\``)
    .replace(
      /^\*\*Progress:\*\*.*$/m,
      `**Progress:** ${drawn.size} of ${ICONS.length} drawn (updated by \`npm run icons\`).`,
    );
  writeFileSync(CHECKLIST, doc);
}

if (backups.length)
  console.log(`(skipped ${backups.length} backup file(s): ${backups.join(', ')})`);

const total = ICONS.length;
console.log(
  `\n${Object.keys(generated).length} drawn by you, ${failed} with problems, ${total} icons in the catalog.`,
);
process.exitCode = failed ? 1 : 0;
